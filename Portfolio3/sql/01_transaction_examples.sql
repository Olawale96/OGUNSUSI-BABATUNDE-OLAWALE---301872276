-- Portfolio 3: transaction control examples
-- Run against database mun_srrms. These examples use a dedicated demo table
-- so that coursework tests do not alter real student registrations.

SET search_path TO mun_srrms, public;

-- SECTION A: create a small transaction test table (safe to re-run).
CREATE TABLE IF NOT EXISTS transaction_demo_log (
    demo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_description TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- SECTION B: COMMIT — execute this block, then inspect the inserted row.
BEGIN;
INSERT INTO transaction_demo_log(event_description)
VALUES ('Portfolio 3: committed transaction');
COMMIT;

SELECT * FROM transaction_demo_log
WHERE event_description = 'Portfolio 3: committed transaction'
ORDER BY demo_id DESC;

-- SECTION C: ROLLBACK — execute this block, then run the SELECT below.
BEGIN;
INSERT INTO transaction_demo_log(event_description)
VALUES ('Portfolio 3: this row must be rolled back');
ROLLBACK;

SELECT * FROM transaction_demo_log
WHERE event_description = 'Portfolio 3: this row must be rolled back';
-- Expected: zero rows. Verify this in your own database.

-- SECTION D: SAVEPOINT — execute the whole block.
BEGIN;
INSERT INTO transaction_demo_log(event_description)
VALUES ('Portfolio 3: retained before savepoint');

SAVEPOINT before_optional_action;

INSERT INTO transaction_demo_log(event_description)
VALUES ('Portfolio 3: optional action to undo');

ROLLBACK TO SAVEPOINT before_optional_action;

INSERT INTO transaction_demo_log(event_description)
VALUES ('Portfolio 3: retained after savepoint');

COMMIT;

SELECT * FROM transaction_demo_log
WHERE event_description LIKE 'Portfolio 3: %'
ORDER BY demo_id;

