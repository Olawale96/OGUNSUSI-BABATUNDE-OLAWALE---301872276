-- MUN-SRRMS Portfolio 1 schema
-- Target: PostgreSQL 14+
-- Run against the dedicated mun_srrms database.
BEGIN;

CREATE SCHEMA IF NOT EXISTS mun_srrms;
SET search_path TO mun_srrms, public;

CREATE TABLE department (
    department_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_code VARCHAR(12) NOT NULL UNIQUE,
    department_name VARCHAR(120) NOT NULL UNIQUE,
    CONSTRAINT department_code_nonblank CHECK (btrim(department_code) <> ''),
    CONSTRAINT department_name_nonblank CHECK (btrim(department_name) <> '')
);

CREATE TABLE programme (
    programme_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id  INTEGER NOT NULL REFERENCES department(department_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    programme_code VARCHAR(20) NOT NULL UNIQUE,
    programme_name VARCHAR(160) NOT NULL,
    award_level    VARCHAR(20) NOT NULL,
    CONSTRAINT programme_name_nonblank CHECK (btrim(programme_name) <> ''),
    CONSTRAINT programme_award_level_check CHECK (award_level IN ('ND', 'HND', 'BSc', 'BEng', 'MSc', 'MTech', 'PhD')),
    CONSTRAINT programme_department_name_unique UNIQUE (department_id, programme_name)
);

CREATE TABLE lecturer (
    lecturer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_number VARCHAR(20) NOT NULL UNIQUE,
    department_id INTEGER NOT NULL REFERENCES department(department_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    CONSTRAINT lecturer_staff_nonblank CHECK (btrim(staff_number) <> ''),
    CONSTRAINT lecturer_email_nonblank CHECK (btrim(email) <> '')
);

CREATE TABLE student (
    student_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matric_number VARCHAR(24) NOT NULL UNIQUE,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    date_of_birth DATE,
    admission_date DATE NOT NULL,
    programme_id INTEGER NOT NULL REFERENCES programme(programme_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    CONSTRAINT student_matric_nonblank CHECK (btrim(matric_number) <> ''),
    CONSTRAINT student_email_nonblank CHECK (btrim(email) <> ''),
    CONSTRAINT student_status_check CHECK (status IN ('active', 'suspended', 'withdrawn', 'graduated')),
    CONSTRAINT student_dob_before_admission CHECK (date_of_birth IS NULL OR date_of_birth < admission_date)
);

CREATE TABLE course (
    course_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code VARCHAR(16) NOT NULL UNIQUE,
    course_title VARCHAR(160) NOT NULL,
    credit_units SMALLINT NOT NULL,
    department_id INTEGER NOT NULL REFERENCES department(department_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT course_code_nonblank CHECK (btrim(course_code) <> ''),
    CONSTRAINT course_title_nonblank CHECK (btrim(course_title) <> ''),
    CONSTRAINT course_credit_units_check CHECK (credit_units BETWEEN 1 AND 6)
);

CREATE TABLE semester (
    semester_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year VARCHAR(9) NOT NULL,
    term VARCHAR(16) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    CONSTRAINT semester_term_check CHECK (term IN ('First', 'Second', 'Summer')),
    CONSTRAINT semester_dates_check CHECK (end_date >= start_date),
    CONSTRAINT semester_year_term_unique UNIQUE (academic_year, term)
);

CREATE TABLE course_offering (
    offering_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id INTEGER NOT NULL REFERENCES course(course_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    semester_id INTEGER NOT NULL REFERENCES semester(semester_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    lecturer_id INTEGER NOT NULL REFERENCES lecturer(lecturer_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    section_code VARCHAR(10) NOT NULL DEFAULT 'A',
    capacity INTEGER NOT NULL DEFAULT 100,
    CONSTRAINT offering_section_nonblank CHECK (btrim(section_code) <> ''),
    CONSTRAINT offering_capacity_check CHECK (capacity BETWEEN 1 AND 1000),
    CONSTRAINT offering_course_semester_section_unique UNIQUE (course_id, semester_id, section_code)
);

CREATE TABLE enrolment (
    enrolment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES student(student_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    offering_id INTEGER NOT NULL REFERENCES course_offering(offering_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    registration_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'registered',
    CONSTRAINT enrolment_status_check CHECK (status IN ('registered', 'dropped', 'completed')),
    CONSTRAINT enrolment_student_offering_unique UNIQUE (student_id, offering_id)
);

CREATE TABLE result (
    result_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrolment_id INTEGER NOT NULL UNIQUE REFERENCES enrolment(enrolment_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    mark NUMERIC(5,2) NOT NULL,
    grade VARCHAR(2) NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT result_mark_check CHECK (mark BETWEEN 0 AND 100),
    CONSTRAINT result_grade_check CHECK (grade IN ('A', 'B', 'C', 'D', 'E', 'F'))
);

-- Explicit indexes on foreign-key columns commonly used for joins.
-- UNIQUE constraints already create indexes for their constrained columns.
CREATE INDEX idx_programme_department ON programme(department_id);
CREATE INDEX idx_lecturer_department ON lecturer(department_id);
CREATE INDEX idx_student_programme ON student(programme_id);
CREATE INDEX idx_course_department ON course(department_id);
CREATE INDEX idx_offering_course ON course_offering(course_id);
CREATE INDEX idx_offering_semester ON course_offering(semester_id);
CREATE INDEX idx_offering_lecturer ON course_offering(lecturer_id);
CREATE INDEX idx_enrolment_student ON enrolment(student_id);
CREATE INDEX idx_enrolment_offering ON enrolment(offering_id);

COMMIT;
